/* 按 id（官网 ename）查英雄；找不到返回 null。 */
WZ.heroById = function (id) {
  var n = Number(id);
  if (!isFinite(n)) { return null; }
  for (var i = 0; i < WZ.HEROES.length; i++) {
    if (WZ.HEROES[i].id === n) { return WZ.HEROES[i]; }
  }
  return null;
};

/* 搜索英雄：空查询返回全部；大小写不敏感；
   排序权重 name 前缀(0) < idName 前缀(1) < 包含(2)，同权重按 id 升序。 */
WZ.searchHeroes = function (query) {
  var all = WZ.HEROES;
  var q = (query === null || query === undefined) ? "" : String(query);
  q = q.replace(/^\s+|\s+$/g, "").toLowerCase();
  if (!q) { return all.slice(); }
  var hits = [];
  for (var i = 0; i < all.length; i++) {
    var h = all[i];
    var name = String(h.name || "").toLowerCase();
    var idName = String(h.idName || "").toLowerCase();
    var weight = -1;
    if (name.indexOf(q) === 0) {
      weight = 0;
    } else if (idName.indexOf(q) === 0) {
      weight = 1;
    } else if (name.indexOf(q) >= 0 || idName.indexOf(q) >= 0) {
      weight = 2;
    } else {
      var vs = (h.pinyin && h.pinyin.variants) || [];
      for (var k = 0; k < vs.length; k++) {
        if (String(vs[k]).toLowerCase().indexOf(q) >= 0) { weight = 2; break; }
      }
    }
    if (weight >= 0) { hits.push({ w: weight, h: h }); }
  }
  hits.sort(function (a, b) { return (a.w - b.w) || (a.h.id - b.h.id); });
  var out = [];
  for (var j = 0; j < hits.length; j++) { out.push(hits[j].h); }
  return out;
};
